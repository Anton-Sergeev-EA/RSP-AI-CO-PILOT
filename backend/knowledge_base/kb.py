STOPWORDS = {
    "что", "как", "это", "для", "или", "при", "если", "его", "она", "они",
    "такое", "такой", "какие", "какой", "сейчас", "уже", "есть", "быть",
    "про", "все", "всё", "этот", "эта", "тут", "там", "нам", "вам",
}


def _score(entry, query_tokens):
    text_lower = (entry["text"] + " " + " ".join(entry["tags"])).lower()
    return sum(1 for t in query_tokens if t in text_lower)


def retrieve(query, top_k=3):
    """Простой keyword-based retrieval по локальной базе знаний."""
    query_tokens = [
        t.strip(".,?!:;") for t in query.lower().split()
        if len(t) > 2 and t.strip(".,?!:;") not in STOPWORDS
    ]
    scored = [(entry, _score(entry, query_tokens)) for entry in KB]
    scored = [s for s in scored if s[1] > 0]
    scored.sort(key=lambda s: -s[1])
    return [e for e, _ in scored[:top_k]]


def retrieve_by_ids(ids):
    return [e for e in KB if e["id"] in ids]
